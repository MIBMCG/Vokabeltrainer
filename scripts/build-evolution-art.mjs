import {createHash} from 'node:crypto';
import {mkdir, readFile, writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceRoot = resolve(root, 'docs/design/avatar-evolution-sources');
const outputRoot = resolve(root, 'trainer/assets/avatar-evolution');
const manifestPath = resolve(root, 'src/trainer/avatar/evolution-art-manifest.js');
const widths = Object.freeze([256, 512, 768]);
const sources = Object.freeze([
  'dragon-stage-1-v3.png',
  'dragon-stage-2-v3.png',
  'dragon-stage-3-v1.png',
  'dragon-stage-4-v2.png',
]);

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function sharpLibrary() {
  try {
    // Build-time dependency only. CODEX's bundled module path can be supplied
    // through NODE_PATH or SHARP_MODULE; the shipped app imports neither.
    return require(process.env.SHARP_MODULE || 'sharp');
  } catch (error) {
    throw new Error('Sharp is required only to build evolution art. Set SHARP_MODULE or NODE_PATH to a Sharp installation.', {cause: error});
  }
}

function manifestModule(value, smallUrls) {
  return `// Generated by scripts/build-evolution-art.mjs. Do not edit by hand.\n`
    + `function deepFreeze(value) {\n`
    + `  if (value && typeof value === 'object' && !Object.isFrozen(value)) {\n`
    + `    for (const child of Object.values(value)) deepFreeze(child);\n`
    + `    Object.freeze(value);\n`
    + `  }\n`
    + `  return value;\n`
    + `}\n\n`
    + `export const EVOLUTION_ART = deepFreeze(${JSON.stringify(value, null, 2)});\n\n`
    + `export const EVOLUTION_SMALL_URLS = Object.freeze(${JSON.stringify(smallUrls, null, 2)});\n`;
}

export async function buildEvolutionArt() {
  const sharp = sharpLibrary();
  const assets = {};
  const sourceFacts = [];
  const smallUrls = [];
  let originalBytes = 0;
  let smallBytes = 0;
  let allBytes = 0;
  await mkdir(outputRoot, {recursive: true});

  for (let index = 0; index < sources.length; index += 1) {
    const stage = index + 1;
    const sourceName = sources[index];
    const source = await readFile(resolve(sourceRoot, sourceName));
    const provenance = JSON.parse(await readFile(resolve(sourceRoot, sourceName.replace(/\.png$/u, '.json')), 'utf8'));
    const hash = sha256(source);
    if (provenance.status !== 'selected-production-source' || provenance.sha256 !== hash || provenance.source !== sourceName) {
      throw new Error(`Source provenance mismatch: ${sourceName}`);
    }
    const metadata = await sharp(source).metadata();
    const alpha = (await sharp(source).stats()).channels[3];
    if (metadata.format !== 'png' || metadata.channels !== 4 || !metadata.hasAlpha || !alpha || alpha.min !== 0 || alpha.max < 1) {
      throw new Error(`Selected source lacks transparent image content: ${sourceName}`);
    }
    const key = `dragon-stage-${stage}`;
    const variants = [];
    for (const width of widths) {
      const height = Math.round(metadata.height * width / metadata.width);
      if (width > metadata.width || height > metadata.height) throw new Error(`Upscaling refused: ${sourceName} at ${width}px`);
      const filename = `${key}-${width}.webp`;
      const bytes = await sharp(source).resize({width, height, fit: 'fill', kernel: 'lanczos3'})
        .webp({quality: 88, effort: 6, alphaQuality: 100}).toBuffer();
      const result = await sharp(bytes).metadata();
      const resultAlpha = (await sharp(bytes).stats()).channels[3];
      if (result.format !== 'webp' || result.width !== width || result.height !== height || !result.hasAlpha || resultAlpha.min !== 0 || resultAlpha.max < 1) {
        throw new Error(`Invalid transparent derivative: ${filename}`);
      }
      await writeFile(resolve(outputRoot, filename), bytes);
      const url = `../../../trainer/assets/avatar-evolution/${filename}`;
      variants.push({width, height, bytes: bytes.length, sha256: sha256(bytes), url});
      allBytes += bytes.length;
      if (width === 256) {
        smallBytes += bytes.length;
        smallUrls.push(url);
      }
    }
    assets[key] = {
      key, sourceName, sourceWidth: metadata.width, sourceHeight: metadata.height,
      sourceBytes: source.length, sourceSha256: hash,
      width: metadata.width, height: metadata.height,
      variants, fallbackUrl: variants[0].url,
    };
    sourceFacts.push({stage, sourceName, sourceBytes: source.length, sourceSha256: hash,
      width: metadata.width, height: metadata.height});
    originalBytes += source.length;
  }

  const report = {
    generator: 'scripts/build-evolution-art.mjs',
    sourceFacts,
    totals: {originalBytes, smallBytes, allBytes},
    derivatives: Object.values(assets).flatMap(({variants}) => variants),
  };
  await writeFile(manifestPath, manifestModule({assets}, smallUrls), 'utf8');
  await writeFile(resolve(outputRoot, 'build-report.json'), `${JSON.stringify(report, null, 2)}\n`, 'utf8');
  return report;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const report = await buildEvolutionArt();
  process.stdout.write(`${JSON.stringify(report.totals)}\n`);
}
